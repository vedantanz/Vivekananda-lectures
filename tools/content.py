BRIDGE = [
    ("The moth and the flame (¶4)",
     "Psychologists describe hedonic adaptation: after a gain or a loss, people tend to drift back towards "
     "their usual level of happiness, so each new pleasure soon feels ordinary. Neuroscience also distinguishes "
     "“wanting” from “liking”: the brain systems that drive craving can grow stronger even "
     "when the pleasure itself does not. That is close to his picture of returning “again and again with "
     "freshened energy.”"),
    ("A mother’s love (¶7)",
     "Much of our emotional life runs on conditioned responses and attachment patterns that operate below "
     "conscious choice. Vivekananda’s point is honest seeing: what we call love may also contain compulsion. "
     "This is not advice to remain in harm’s way. Freedom, in Vedanta, includes the strength to set "
     "boundaries, and anyone in a harmful relationship deserves support from trusted people or professionals."),
    ("Covering the wound (¶10)",
     "Research on emotion regulation suggests that habitually suppressing feelings tends to go with poorer "
     "wellbeing than reappraising them honestly. Acceptance-based therapies likewise invite people to face "
     "difficult experience openly. Both resonate with his warning that sores hidden under cloth of gold do "
     "not heal."),
    ("Dissatisfaction as a beginning (¶12)",
     "Models of behaviour change describe a stage of honest recognition (“contemplation”) that comes "
     "before real change. Vivekananda’s “tremendous dissatisfaction” is not despair: it is joined "
     "to the hopeful command “Arise! Awake!”"),
    ("Freedom within (¶18)",
     "Contemplative practices train us to observe thoughts and feelings rather than be driven by them, what "
     "psychologists call decentering. Vedanta goes much further, teaching that the witnessing Self was never "
     "bound. Even a small taste of this inner distance can ease anxiety and restore choice."),
]

