SUMMARY_INTRO = (
    "In this London lecture Swami Vivekananda does not define Maya in the abstract. "
    "He shows it to us, in one scene of ordinary life after another, each ending with the "
    "same quiet refrain: “And this is Maya.” Then he turns the whole picture around. "
    "The very struggle that binds us, he says, is the movement of every being towards freedom, "
    "and that freedom is not far away. It is our own nature."
)

SUMMARY_POINTS = [
    ("Maya is a description of our situation",
     "Life is a battlefield we enter weeping. Childhood dreams recede as we chase them. The senses pull us "
     "back like moths to a flame. The intellect meets walls of time, space and causation. We feel free and "
     "are shown, moment by moment, that we are bound."),
    ("Even love can be bondage",
     "A mother clings to a child who ill-treats her and calls it wonderful love, though she cannot help it. "
     "Narada lives twelve years of marriage, wealth and loss in half an hour. Time, “the avenger,” "
     "swallows saint and sinner alike."),
    ("Two responses to suffering",
     "The “practical” response says: ignore the dark side and cover the wound with cloth of gold. "
     "Vivekananda says this must fail. The other response is a “still small voice” heard in every age "
     "and land, promising a way beyond Maya. Responding to it is what he calls religion."),
    ("Religion begins with honest dissatisfaction",
     "Like the Buddha under the Bo-tree, the seeker refuses a life of patchwork and resolves to find the truth. "
     "The Katha Upanishad sums it up: Arise! Awake! The path is like a razor’s edge, yet do not despair."),
    ("Freedom is the golden thread",
     "Every religion, from the simplest to the most philosophical, points to a being who is free of nature’s "
     "laws. The universe rises in freedom, rests in freedom and melts into freedom. Saint and sinner are both "
     "moving towards it; good and bad differ only in degree."),
    ("The Vedantic answer: nearer, my God, to me",
     "Vedanta brings the free Being closer and closer, from heaven to nature to the body, until it is found as "
     "the Self of our own self. Maya never really bound us. When this is realised, the prison-house of the "
     "world becomes a playground."),
]

